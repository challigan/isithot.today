describe('appCopySwift', () => {
  const swift = appCopySwift();

  it('goes into IsItModel, with the header first', () => {
    expect(APP_COPY_PATH).toBe(
      'apps/ios/Packages/IsItCore/Sources/IsItModel/Generated/AppCopy.swift',
    );
    expect(swift.split('\n')[0]).toBe(
      '// Generated by pnpm mobile:generate from packages/mobile/src/appCopy.ts. Do not edit.',
    );
    expect(APP_COPY_SOURCE).toBe('packages/mobile/src/appCopy.ts');
  });

  it("has every string, in appCopy.ts's order, but those App Intents reads as literals", () => {
    const names = swift
      .split('\n')
      .map((l) => /^ {2}public static (?:let|func) (\w+)/.exec(l)?.[1])
      .filter(Boolean);
    expect(APP_INTENT_KEYS).toEqual(['intentTitle', 'intentPhrase']);
    expect(names).toEqual(
      Object.keys(APP_COPY).filter((k) => !APP_INTENT_KEYS.includes(k as AppCopyKey)),
    );
    // The App Shortcut's words stay out: as a runtime String or function, neither could become
    // the intent's title or its phrase.
    for (const key of APP_INTENT_KEYS) expect(swift).not.toContain(key);
    expect(swift).not.toContain('Will it snow tomorrow');
    expect(appCopySwift({ intentTitle: 'x', kept: 'y' })).not.toContain('intentTitle');
  });

  it('makes a string with slots a function that fills them', () => {
    expect(appCopyMember('placeButtonLabel', APP_COPY.placeButtonLabel)).toEqual([
      '  public static func placeButtonLabel(place: String) -> String {',
      '    "Place: \\(place). Change place."',
      '  }',
    ]);
    expect(appCopyMember('version', APP_COPY.version)).toEqual([
      '  public static func version(version: String, build: String) -> String {',
      '    "Version \\(version) (\\(build))"',
      '  }',
    ]);
    // A signature too long for 100 columns has a parameter on each line.
    expect(appCopyMember('weekRowLabel', APP_COPY.weekRowLabel)).toEqual([
      '  public static func weekRowLabel(',
      '    day: String,',
      '    amount: String,',
      '    band: String,',
      '    agreement: String',
      '  ) -> String {',
      '    "\\(day), \\(amount), \\(band), \\(agreement)"',
      '  }',
    ]);
    expect(appCopyMember('reportAdMail', APP_COPY.reportAdMail)[1]).toBe(
      '    "Time: \\(time)\\nPlace: \\(place)\\nWhat was wrong with the ad:\\n"',
    );
    expect(swift).toContain(
      '\n\n  public static func upgradeRow(price: String) -> String {\n' +
        '    "No ads, plus widgets for your home and lock screen · \\(price)"\n  }\n\n',
    );
  });

  it('escapes apostrophes, quotes, $ and backslashes as Swift needs', () => {
    expect(appCopyMember('a', "You're “here”, $5")).toEqual([
      '  public static let a = "You\'re “here”, $5"',
    ]);
    expect(appCopyMember('b', 'say "\\(x)" in {place}')).toEqual([
      '  public static func b(place: String) -> String {',
      '    "say \\"\\\\(x)\\" in \\(place)"',
      '  }',
    ]);
    expect(swift).toContain(`  public static let testFailed = ${swiftString(APP_COPY.testFailed)}`);
    expect(swift).toContain('"Couldn\'t send a test notification. Try again later."');
  });

  it('throws on a key or slot that is not a Swift name', () => {
    expect(() => appCopySwift({ 'last-view': 'x' })).toThrow(/Not a lower camel case/);
    expect(() => appCopySwift({ a: 'Hello {First name}' })).toThrow(/Not a lower camel case/);
  });

  it('is the same every time, with long strings whole on their own lines', () => {
    expect(appCopySwift()).toBe(swift);
    fitsColumns(swift);
  });
});

