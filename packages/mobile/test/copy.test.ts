/** The lines between `start` and the next line that is exactly `end`. */
function block(swift: string, start: string, end: string): string[] {
  const lines = swift.split('\n');
  const from = lines.indexOf(start);
  expect(from, start).toBeGreaterThanOrEqual(0);
  return lines.slice(from + 1, lines.indexOf(end, from));
}

/** Within 100 columns, but for a string literal alone on its line, which can't be broken. */
function fitsColumns(swift: string) {
  for (const line of swift.split('\n')) {
    if (line.length > 100) expect(line.trim()).toMatch(/^"[^"]*(\\"[^"]*)*"$/);
  }
}

