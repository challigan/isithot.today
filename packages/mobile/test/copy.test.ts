describe('questionsSwift', () => {
  const swift = questionsSwift();
  const templates = questionTemplates();

  it('goes into IsItModel, with the header first', () => {
    expect(QUESTIONS_PATH).toBe(
      'apps/ios/Packages/IsItCore/Sources/IsItModel/Generated/Questions.swift',
    );
    expect(swift.split('\n')[0]).toBe(generatedHeader(QUESTIONS_SOURCE));
    expect(swift.split('\n')[0]).toBe(
      '// Generated by pnpm mobile:generate from packages/core/src/copy.ts (question). Do not edit.',
    );
  });

  it('asks core for every view, with and without a place, tomorrow or not', () => {
    expect(templates).toHaveLength(VIEWS.length * 4);
    expect(templates.map((t) => t.text)).toEqual([
      'Is it snowing right now?',
      'Is it snowing in {place} right now?',
      'Is it snowing right now?',
      'Is it snowing in {place} right now?',
      'Will it snow today?',
      'Will it snow in {place} today?',
      'Will it snow tomorrow?',
      'Will it snow in {place} tomorrow?',
      'Will it snow this week?',
      'Will it snow in {place} this week?',
      'Will it snow this week?',
      'Will it snow in {place} this week?',
    ]);
    for (const t of templates) {
      expect(t.text).toBe(question(t.withPlace ? PLACE_SLOT : null, t.view, 'snow', t.tomorrow));
    }
  });

  it('fills a template as core words the question, whatever the place holds', () => {
    // What the Swift does: the slot replaced once, by the name as it is.
    for (const name of ['Leeds', "St John's", '“Quoted”', '$1 $& $$', 'a\\b \\(x)', '{place}']) {
      for (const t of templates.filter((t) => t.withPlace)) {
        expect(t.text.replace(PLACE_SLOT, () => name)).toBe(
          question(name, t.view, 'snow', t.tomorrow),
        );
      }
    }
  });

  it('switches over every case, in order', () => {
    expect(block(swift, '    switch (view, tomorrow, withPlace) {', '    }')).toEqual(
      templates.map(
        (t) => `    case (.${t.view}, ${t.tomorrow}, ${t.withPlace}): ${swiftString(t.text)}`,
      ),
    );
    expect(swift).toContain('  public static let slot = "{place}"');
    expect(swift).toContain(
      '  public static func snow(view: AppView, place: String?, tomorrow: Bool) -> String {',
    );
  });

  it('is the same every time, within 100 columns', () => {
    expect(questionsSwift()).toBe(swift);
    for (const line of swift.split('\n')) expect(line.length).toBeLessThanOrEqual(100);
  });
});

