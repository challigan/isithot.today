/** The lines between `start` and the next line that is exactly `end`. */
function block(swift: string, start: string, end: string): string[] {
  const lines = swift.split('\n');
  const from = lines.indexOf(start);
  expect(from, start).toBeGreaterThanOrEqual(0);
  return lines.slice(from + 1, lines.indexOf(end, from));
}

/** Within 100 columns, but for a string literal alone on its line, which can't be broken. */
function fitsColumns(swift: string) {
  for (const line of swift.split('\n')) {
    if (line.length > 100) expect(line.trim()).toMatch(/^"[^"]*(\\"[^"]*)*"$/);
  }
}

describe('coreCopySwift', () => {
  const swift = coreCopySwift();

  it('goes into IsItModel, with the header first', () => {
    expect(CORE_COPY_PATH).toBe(
      'apps/ios/Packages/IsItCore/Sources/IsItModel/Generated/CoreCopy.swift',
    );
    expect(swift.split('\n')[0]).toBe(
      '// Generated by pnpm mobile:generate from packages/core/src/copy.ts. Do not edit.',
    );
    expect(swift.split('\n')[0]).toBe(generatedHeader(CORE_COPY_SOURCE));
    expect(swift.endsWith('}\n')).toBe(true);
  });

  it("has the COPY keys the app uses, in COPY's order, with core's words", () => {
    const keys = Object.keys(COPY).filter((k) => (CORE_COPY_KEYS as readonly string[]).includes(k));
    expect(keys).toHaveLength(CORE_COPY_KEYS.length);
    const lets = swift
      .split('\n')
      .filter((l) => /^ {2}public static let \w+ =/.test(l))
      .map((l) => l.trim().split(' ')[3]);
    expect(lets).toEqual([...keys, 'snowUnitsLabel', 'tomorrowLabel']);
    expect(swift).toContain('  public static let notAvailable = "Not available right now."');
    expect(swift).toContain('  public static let checking = "Checking…"');
    // The section 10.9 list, every one there.
    for (const key of [
      'searchPlaceholder',
      'outboundIntro',
      'stale',
      'metOfficeWarnings',
    ] as const) {
      expect(swift).toContain(`  public static let ${key} = ${swiftString(COPY[key])}`);
    }
  });

  it('writes a long string whole, on a line of its own', () => {
    expect(swift).toContain(
      `  public static let metOfficeCredit =\n    ${swiftString(COPY.metOfficeCredit)}\n`,
    );
    fitsColumns(swift);
  });

  it("writes the snow units' label once, from UNITS_LABELS", () => {
    expect(UNITS_LABELS.snow).toBe(COPY.snowUnitsLabel);
    expect(swift.match(/public static let snowUnitsLabel/g)).toHaveLength(1);
    expect(swift).toContain('  public static let snowUnitsLabel = "Snow units"');
  });

  it("labels the views in VIEWS' order, and the units, bands, reasons and errors in core's", () => {
    expect(block(swift, '    switch view {', '    }')).toEqual([
      '    case .now: "Now"',
      '    case .today: "Today"',
      '    case .week: "This week"',
    ]);
    expect(VIEWS).toEqual(['now', 'today', 'week']);
    expect(block(swift, '    switch units {', '    }')).toEqual([
      '    case .c: "cm"',
      '    case .f: "in"',
    ]);
    expect(block(swift, '    switch band {', '    }')).toEqual([
      ...Object.entries(SNOW_BAND_LABELS).map(([k, v]) => `    case .${k}: ${swiftString(v)}`),
      '    case .unknown: nil',
    ]);
    expect(block(swift, '    switch reason {', '    }')).toEqual([
      ...Object.entries(SNOW_REASON_LABELS).map(([k, v]) => `    case .${k}: ${swiftString(v)}`),
      '    case .unknown: nil',
    ]);
    expect(block(swift, '    switch code {', '    }')).toEqual([
      ...Object.entries(ERROR_MESSAGES).map(([k, v]) => `    case "${k}": ${swiftString(v)}`),
      '    default: nil',
    ]);
  });

  it('is the same every time', () => {
    expect(coreCopySwift()).toBe(swift);
  });
});

describe('questionsSwift', () => {
  const swift = questionsSwift();
  const templates = questionTemplates();

  it('goes into IsItModel, with the header first', () => {
    expect(QUESTIONS_PATH).toBe(
      'apps/ios/Packages/IsItCore/Sources/IsItModel/Generated/Questions.swift',
    );
    expect(swift.split('\n')[0]).toBe(generatedHeader(QUESTIONS_SOURCE));
    expect(swift.split('\n')[0]).toBe(
      '// Generated by pnpm mobile:generate from packages/core/src/copy.ts (question). Do not edit.',
    );
  });

  it('asks core for every view, with and without a place, tomorrow or not', () => {
    expect(templates).toHaveLength(VIEWS.length * 4);
    expect(templates.map((t) => t.text)).toEqual([
      'Is it snowing right now?',
      'Is it snowing in {place} right now?',
      'Is it snowing right now?',
      'Is it snowing in {place} right now?',
      'Will it snow today?',
      'Will it snow in {place} today?',
      'Will it snow tomorrow?',
      'Will it snow in {place} tomorrow?',
      'Will it snow this week?',
      'Will it snow in {place} this week?',
      'Will it snow this week?',
      'Will it snow in {place} this week?',
    ]);
    for (const t of templates) {
      expect(t.text).toBe(question(t.withPlace ? PLACE_SLOT : null, t.view, 'snow', t.tomorrow));
    }
  });

  it('fills a template as core words the question, whatever the place holds', () => {
    // What the Swift does: the slot replaced once, by the name as it is.
    for (const name of ['Leeds', "St John's", '“Quoted”', '$1 $& $$', 'a\\b \\(x)', '{place}']) {
      for (const t of templates.filter((t) => t.withPlace)) {
        expect(t.text.replace(PLACE_SLOT, () => name)).toBe(
          question(name, t.view, 'snow', t.tomorrow),
        );
      }
    }
  });

  it('switches over every case, in order', () => {
    expect(block(swift, '    switch (view, tomorrow, withPlace) {', '    }')).toEqual(
      templates.map(
        (t) => `    case (.${t.view}, ${t.tomorrow}, ${t.withPlace}): ${swiftString(t.text)}`,
      ),
    );
    expect(swift).toContain('  public static let slot = "{place}"');
    expect(swift).toContain(
      '  public static func snow(view: AppView, place: String?, tomorrow: Bool) -> String {',
    );
  });

  it('is the same every time, within 100 columns', () => {
    expect(questionsSwift()).toBe(swift);
    for (const line of swift.split('\n')) expect(line.length).toBeLessThanOrEqual(100);
  });
});

describe('APP_COPY', () => {
  const entries = Object.entries(APP_COPY);

  it('has section 10.9’s strings, without the removed websites section', () => {
    expect(APP_COPY.placeButtonLabel).toBe('Place: {place}. Change place.');
    expect(APP_COPY.offline).toBe("You're offline. Showing the forecast from {time}.");
    expect(APP_COPY.unitsFootnote).toBe('Temperatures follow: cm with °C, inches with °F.');
    expect(APP_COPY.widgetName).toBe('Snow forecast');
    expect(APP_COPY.intentPhrase).toBe('Will it snow tomorrow in {app}?');
    // Every key in section 10.9's table.
    const table = [
      ...['placeButtonLabel', 'settings', 'recent', 'slugGone', 'offline', 'staleApp'],
      ...['cardChosen', 'cardApprox', 'turnOn', 'notNow', 'search', 'upgradeRow'],
      ...['upgradeTitle', 'upgradeBody', 'familySharing', 'thanks', 'pending', 'restore'],
      ...['restored', 'nothingToRestore', 'unitsFootnote', 'notifications', 'evening'],
      ...['eveningNote', 'morning', 'morningNote', 'possible', 'possibleNote', 'notifyPlace'],
      ...['notifyPlaceOnScreen', 'notifyPlaceMyLocation', 'notifyFollows', 'needsPlace'],
      ...['sendTest', 'testSent', 'testLimited', 'testFailed', 'notifyFooter', 'notifyDenied'],
      ...['openSettings', 'privacyChoices', 'yourPrivacy', 'privacyPolicy'],
      ...['keptForNotifications', 'deleteMyData', 'reportAd', 'reportAdBody', 'copyAddress'],
      ...['copied', 'credits', 'terms', 'contactUs', 'support', 'version', 'widgetName'],
      ...['widgetDescription', 'widgetLocked', 'widgetStale', 'agreementShort'],
      ...['intentTitle', 'intentPhrase'],
    ];
    for (const key of table) expect(APP_COPY, key).toHaveProperty(key);
    // `privacy*`: the "Your privacy" lines, five of them.
    const privacy = Object.keys(APP_COPY).filter((k) => /^privacy[A-Z]/.test(k));
    expect(privacy.filter((k) => !table.includes(k))).toHaveLength(5);
    for (const [key, text] of entries) {
      expect(`${key} ${text}`).not.toMatch(
        /\b(websites?|isithot|isitwet|isitwindy|hot|wet|wind|windy|rain|rainy|android)\b/i,
      );
    }
  });

  it('names its slots, and only these strings have them', () => {
    const slotted = Object.fromEntries(
      entries.filter(([, t]) => templateSlots(t).length).map(([k, t]) => [k, templateSlots(t)]),
    );
    expect(slotted).toEqual({
      placeButtonLabel: ['place'],
      offline: ['time'],
      upgradeRow: ['price'],
      upgradeSettings: ['price'],
      notifyPlaceOnScreen: ['place'],
      reportAdSubject: ['version'],
      reportAdMail: ['time', 'place'],
      reportAdBody: ['email'],
      version: ['version', 'build'],
      agreementShort: ['snowy', 'total'],
      intentPhrase: ['app'],
    });
  });

  it('says "notification", never "alert", "warning" or "danger", but for the footer', () => {
    for (const [key, text] of entries) {
      if (key === 'notifyFooter') continue;
      expect(text, key).not.toMatch(/alert|warning|danger/i);
    }
    expect(APP_COPY.notifyFooter).toMatch(/^These are forecasts, not official warnings\./);
  });

  it('has no stray spaces', () => {
    for (const [key, text] of entries) {
      expect(text, key).not.toMatch(/^\s|[ \t]$| {2}/m);
    }
  });

  it('is in British English', () => {
    const american =
      /\b(colors?|centers?|favorites?|licenses?|canceled|canceling|gray|catalog|program|\w+iz(e|es|ed|ing))\b/i;
    for (const [key, text] of entries) expect(text, key).not.toMatch(american);
    expect(APP_COPY.credits).toBe('Credits and licences');
  });

  it('is in sentence case: capitals only to start a sentence, and for names', () => {
    const names = [
      'Apple Account',
      'Family Sharing',
      'Privacy choices',
      'Settings',
      'Safari',
      'Met Office',
      'Apple',
      'Google',
      'UK',
      '°C',
      '°F',
    ];
    for (const [key, text] of entries) {
      let rest = text;
      for (const name of names) rest = rest.split(name).join('');
      for (const match of rest.matchAll(/\S+/g)) {
        const word = match[0];
        if (!/[A-Z]/.test(word)) continue;
        const before = rest.slice(0, match.index);
        const startsSentence = before === '' || /[.?!]\s+$|\n$/.test(before);
        expect(startsSentence, `${key}: "${word}" in ${JSON.stringify(text)}`).toBe(true);
        expect(word, `${key}: "${word}"`).toMatch(/^[A-Z][^A-Z]*$/);
      }
    }
  });
});

describe('appCopySwift', () => {
  const swift = appCopySwift();

  it('goes into IsItModel, with the header first', () => {
    expect(APP_COPY_PATH).toBe(
      'apps/ios/Packages/IsItCore/Sources/IsItModel/Generated/AppCopy.swift',
    );
    expect(swift.split('\n')[0]).toBe(
      '// Generated by pnpm mobile:generate from packages/mobile/src/appCopy.ts. Do not edit.',
    );
    expect(APP_COPY_SOURCE).toBe('packages/mobile/src/appCopy.ts');
  });

  it("has every string, in appCopy.ts's order, but those App Intents reads as literals", () => {
    const names = swift
      .split('\n')
      .map((l) => /^ {2}public static (?:let|func) (\w+)/.exec(l)?.[1])
      .filter(Boolean);
    expect(APP_INTENT_KEYS).toEqual(['intentTitle', 'intentPhrase']);
    expect(names).toEqual(
      Object.keys(APP_COPY).filter((k) => !APP_INTENT_KEYS.includes(k as AppCopyKey)),
    );
    // The App Shortcut's words stay out: as a runtime String or function, neither could become
    // the intent's title or its phrase.
    for (const key of APP_INTENT_KEYS) expect(swift).not.toContain(key);
    expect(swift).not.toContain('Will it snow tomorrow');
    expect(appCopySwift({ intentTitle: 'x', kept: 'y' })).not.toContain('intentTitle');
  });

  it('makes a string with slots a function that fills them', () => {
    expect(appCopyMember('placeButtonLabel', APP_COPY.placeButtonLabel)).toEqual([
      '  public static func placeButtonLabel(place: String) -> String {',
      '    "Place: \\(place). Change place."',
      '  }',
    ]);
    expect(appCopyMember('version', APP_COPY.version)).toEqual([
      '  public static func version(version: String, build: String) -> String {',
      '    "Version \\(version) (\\(build))"',
      '  }',
    ]);
    expect(appCopyMember('reportAdMail', APP_COPY.reportAdMail)[1]).toBe(
      '    "Time: \\(time)\\nPlace: \\(place)\\nWhat was wrong with the ad:\\n"',
    );
    expect(swift).toContain(
      '\n\n  public static func upgradeRow(price: String) -> String {\n' +
        '    "No ads, plus widgets for your home and lock screen · \\(price)"\n  }\n\n',
    );
  });

  it('escapes apostrophes, quotes, $ and backslashes as Swift needs', () => {
    expect(appCopyMember('a', "You're “here”, $5")).toEqual([
      '  public static let a = "You\'re “here”, $5"',
    ]);
    expect(appCopyMember('b', 'say "\\(x)" in {place}')).toEqual([
      '  public static func b(place: String) -> String {',
      '    "say \\"\\\\(x)\\" in \\(place)"',
      '  }',
    ]);
    expect(swift).toContain(`  public static let testFailed = ${swiftString(APP_COPY.testFailed)}`);
    expect(swift).toContain('"Couldn\'t send a test notification. Try again later."');
  });

  it('throws on a key or slot that is not a Swift name', () => {
    expect(() => appCopySwift({ 'last-view': 'x' })).toThrow(/Not a lower camel case/);
    expect(() => appCopySwift({ a: 'Hello {First name}' })).toThrow(/Not a lower camel case/);
  });

  it('is the same every time, with long strings whole on their own lines', () => {
    expect(appCopySwift()).toBe(swift);
    fitsColumns(swift);
  });
});
