/** The members of `public enum <name> {`, trimmed, to its closing brace at the same indent. */
function members(swift: string, name: string): string[] {
  const lines = swift.split('\n');
  const start = lines.findIndex((l) => l.trim() === `public enum ${name} {`);
  expect(start, name).toBeGreaterThanOrEqual(0);
  const indent = lines[start]!.indexOf('public');
  const end = lines.indexOf(`${' '.repeat(indent)}}`, start);
  return lines
    .slice(start + 1, end)
    .filter((l) => l.startsWith(`${' '.repeat(indent + 2)}public static let`))
    .map((l) => l.trim());
}

