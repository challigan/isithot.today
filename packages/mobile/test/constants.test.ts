describe('contrast', () => {
  it("works out WCAG 2's ratio from the colours", () => {
    expect(rgb('#f6eef9')).toEqual([246, 238, 249]);
    expect(luminance('#000000')).toBe(0);
    expect(luminance('#ffffff')).toBeCloseTo(1, 12);
    expect(contrastRatio('#000000', '#ffffff')).toBeCloseTo(21, 12);
    expect(contrastRatio('#ffffff', '#000000')).toBeCloseTo(21, 12);
    expect(contrastRatio('#777777', '#777777')).toBe(1);
    // WebAIM's checker: #767676 on white is 4.54:1, the lightest grey to pass AA.
    expect(ratioDown(contrastRatio('#767676', '#ffffff'))).toBe(4.54);
  });

  it('rounds down, so a pair under 4.5 never reads as 4.5', () => {
    expect(ratioDown(4.4999)).toBe(4.49);
    expect(ratioDown(4.5)).toBe(4.5);
    expect(ratioDown(4.58)).toBe(4.58);
    expect(ratioDown(13.624742)).toBe(13.62);
  });

  it('throws on a colour that is not #rrggbb', () => {
    for (const bad of ['f6eef9', '#fff', '#f6eef9ff', '#gggggg']) {
      expect(() => rgb(bad)).toThrow(/Not a #rrggbb colour/);
    }
    expect(() => opacity('0.85')).toThrow(/Not a percentage/);
  });
});

describe('palettesSwift', () => {
  const swift = palettesSwift();

  it('goes into IsItModel, where the widget reaches it, with the header first, importing nothing', () => {
    expect(PALETTES_PATH).toBe(
      'apps/ios/Packages/IsItCore/Sources/IsItModel/Generated/Palettes.swift',
    );
    expect(swift.split('\n')[0]).toBe(generatedHeader(PALETTES_SOURCE));
    expect(swift.split('\n')[0]).toBe(
      '// Generated by pnpm mobile:generate from packages/core/src/palettes.ts. Do not edit.',
    );
    expect(swift.split('\n').filter((l) => l.startsWith('import '))).toEqual([]);
  });

  it('meets WCAG AA for body text with every ink, on both ends of the gradient', () => {
    for (const [band, p] of Object.entries(SNOW_PALETTES)) {
      expect(contrastRatio(p.ink, p.g1), band).toBeGreaterThanOrEqual(BODY_TEXT_CONTRAST);
      expect(contrastRatio(p.ink, p.g2), band).toBeGreaterThanOrEqual(BODY_TEXT_CONTRAST);
    }
  });

  it("writes each band's colours, glow and ratios, in core's order", () => {
    const p = SNOW_PALETTES.nosnow;
    expect(paletteArguments(p)).toEqual([
      'g1: 0xf6eef9',
      'g2: 0xe1c9e8',
      'g3: 0xffe3d3',
      'ink: 0x341a3c',
      'pill: 0xf6eef9',
      'glow: 0.85',
      `inkOnG1: ${ratioDown(contrastRatio(p.ink, p.g1))}`,
      `inkOnG2: ${ratioDown(contrastRatio(p.ink, p.g2))}`,
    ]);
    expect(swift).toContain('      inkOnG1: 13.62,\n      inkOnG2: 10.09\n');
    const bands = [...swift.matchAll(/^ {4}public static let (\w+) = Palette\($/gm)].map(
      (m) => m[1],
    );
    expect(bands).toEqual(Object.keys(SNOW_PALETTES));
    expect(swiftHex('#FFFFFF')).toBe('0xffffff');
    expect(opacity('14%')).toBe(0.14);
  });

  it("gives the app's own pages the website's content palette, snow's", () => {
    expect(CONTENT_BAND).toBe('snow');
    expect(swift).toContain(
      "  /// appearances: the website's content pages' (apps/web `LOOKS.snow.content`, its About,\n",
    );
    expect(swift).toContain('  public static let content = Snow.snow\n');
  });

  it('draws a band the app does not know as nosnow', () => {
    expect(UNKNOWN_BAND_DRAWS_AS).toBe('nosnow');
    expect(swift).toContain('    case .nosnow, .unknown: Snow.nosnow\n');
    expect(swift.match(/\.unknown/g)).toHaveLength(1);
  });

  it('is the same every time, within 100 columns', () => {
    expect(palettesSwift()).toBe(swift);
    for (const line of swift.split('\n')) expect(line.length).toBeLessThanOrEqual(100);
  });
});
